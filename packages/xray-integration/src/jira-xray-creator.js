/**
 * @fileoverview jira-xray-creator.js
 *
 * Creates Xray Test issues and Test Execution issues in Jira via the existing
 * Jira MCP integration. Links Test issues to their parent Story issue.
 *
 * Key design decisions:
 *  - Reuses connectToJiraMcp, getJiraCloudId, callJiraTool from packages/jira-integration/src/index.js
 *  - Xray Test issue type ID: 10010 (name: "Test")
 *  - Xray Test Execution issue type ID: 10013 (name: "Test Execution")
 *  - Issue link type: "Test" (ID: 10006) outward="tests" (Test issues TESTS Story issue)
 *  - Duplicate detection: compares summaries against existing Test issues linked to the story
 *  - Initial execution status: TODO / Not Executed — never marks Passed/Failed
 *  - No hardcoded project keys, story IDs, or cloud IDs
 */

import { pathToFileURL } from "node:url";
import path from "node:path";

// ---------------------------------------------------------------------------
// Constants — Xray issue type and link type IDs
// (discovered via Jira MCP probe in AAQA project)
// ---------------------------------------------------------------------------

export const XRAY_TEST_ISSUE_TYPE_ID = "10010";
export const XRAY_TEST_ISSUE_TYPE_NAME = "Test";
export const XRAY_TEST_EXECUTION_TYPE_ID = "10013";
export const XRAY_TEST_EXECUTION_TYPE_NAME = "Test Execution";
export const XRAY_LINK_TYPE_NAME = "Test"; // "tests" outward direction

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/**
 * Lazily load jira-integration index from an arbitrary project root.
 * @param {string} projectRoot
 */
async function loadJiraIntegration(projectRoot) {
  const indexPath = path.join(projectRoot, "packages", "jira-integration", "src", "index.js");
  const { connectToJiraMcp, getJiraCloudId, callJiraTool } = await import(
    pathToFileURL(indexPath).href
  );
  return { connectToJiraMcp, getJiraCloudId, callJiraTool };
}

/**
 * Build the ADF (Atlassian Document Format) description for a Test issue.
 * Falls back to plain string for Jira that doesn't support ADF via MCP.
 *
 * @param {import("./test-case-builder.js").TestCase} tc
 * @returns {string}
 */
function buildTestDescription(tc) {
  const stepLines = (tc.steps || [])
    .map((s) => `Step ${s.step}: ${s.action}\n  → Expected: ${s.expectedResult}`)
    .join("\n");

  return [
    `**Test Case ID:** ${tc.testCaseId}`,
    `**Scenario:** ${tc.scenarioId}`,
    `**Type:** ${tc.type}`,
    `**Priority:** ${tc.priority}`,
    tc.precondition ? `\n**Preconditions:**\n${tc.precondition}` : "",
    tc.testData ? `\n**Test Data:**\n${tc.testData}` : "",
    `\n**Test Steps:**\n${stepLines}`,
    `\n**Expected Outcome:**\n${tc.expectedOutcome}`,
    `\n**Related Story:** ${tc.relatedStory}`,
    tc.relatedAc ? `**Related AC:** ${tc.relatedAc}` : "",
    `\n---\n*Generated by Jira Xray Excel Test Case Generator Agent*`,
  ]
    .filter(Boolean)
    .join("\n");
}

