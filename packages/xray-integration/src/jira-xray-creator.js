/**
 * Detect potential duplicate test issues by checking existing Test issues
 * linked to the story and comparing summaries.
 *
 * @param {object} client  MCP client
 * @param {string} cloudId
 * @param {string} storyKey  e.g. "AAQA-1"
 * @param {import("./test-case-builder.js").TestCase[]} testCases
 * @param {Function} callJiraTool
 * @returns {Promise<{ duplicates: string[], safeToCreate: string[] }>}
 */
export async function detectDuplicateTests(client, cloudId, storyKey, testCases, callJiraTool) {
  let existingTitles = new Set();

  try {
    // Search for existing Test issues linked to this story
    const searchResult = await callJiraTool(client, "searchJira", {
      cloudId,
      jql: `issueType = "${XRAY_TEST_ISSUE_TYPE_NAME}" AND issue in linkedIssues("${storyKey}", "is tested by")`,
      maxResults: 100,
      fields: ["summary"],
    });
    const issues = searchResult?.issues || [];
    for (const issue of issues) {
      const summary = issue.fields?.summary || "";
      existingTitles.add(summary.toLowerCase().trim());
    }
  } catch {
    // searchJira may not be available; skip duplicate detection gracefully
  }

  const duplicates = [];
  const safeToCreate = [];

  for (const tc of testCases) {
    const normalised = tc.title.toLowerCase().trim();
    if (existingTitles.has(normalised)) {
      duplicates.push(tc.testCaseId);
    } else {
      safeToCreate.push(tc.testCaseId);
    }
  }

  return { duplicates, safeToCreate };
}

/**
 * Create a single Xray Test issue in Jira.
 *
 * @param {object} client  MCP client
 * @param {string} cloudId
 * @param {string} projectKey
 * @param {import("./test-case-builder.js").TestCase} tc
 * @param {Function} callJiraTool
 * @returns {Promise<{ key: string, id: string }>}
 */
export async function createXrayTestIssue(client, cloudId, projectKey, tc, callJiraTool) {
  const result = await callJiraTool(client, "createJiraIssue", {
    cloudId,
    projectKey,
    summary: tc.title,
    description: buildTestDescription(tc),
    issueType: XRAY_TEST_ISSUE_TYPE_NAME,
    priority: tc.priority,
    labels: tc.labels ? tc.labels.split(", ").filter(Boolean) : [],
  });

  const key = result?.key || result?.issueKey;
  const id  = result?.id;

  if (!key) {
    throw new Error(`createJiraIssue did not return an issue key for "${tc.title}"`);
  }

  return { key, id };
}

/**
 * Link a Test issue to its parent Story issue.
 * Direction: Test issue TESTS Story issue (outward link).
 *
 * @param {object} client
 * @param {string} cloudId
 * @param {string} testKey    e.g. "AAQA-10"
 * @param {string} storyKey   e.g. "AAQA-1"
 * @param {Function} callJiraTool
 * @returns {Promise<void>}
 */
export async function linkTestToStory(client, cloudId, testKey, storyKey, callJiraTool) {
  await callJiraTool(client, "createJiraIssueLink", {
    cloudId,
    linkType: XRAY_LINK_TYPE_NAME,
    inwardIssue: testKey,  // the Test issue (inward = "is tested by")
    outwardIssue: storyKey, // the Story (outward = "tests")
  });
}

/**
 * Create a Jira Xray Test Execution issue and link all Test issues to it.
 *
 * @param {object} client
 * @param {string} cloudId
 * @param {string} projectKey
 * @param {string} storyKey
 * @param {string[]} testKeys   Array of Jira Test issue keys
 * @param {Function} callJiraTool
 * @returns {Promise<{ key: string, id: string }>}
 */
export async function createXrayTestExecution(client, cloudId, projectKey, storyKey, testKeys, callJiraTool) {
  const summary = `Test Execution for ${storyKey} — Generated by Xray Test Case Generator Agent`;
  const description = [
    `**Story:** ${storyKey}`,
    `**Tests Included:** ${testKeys.join(", ")}`,
    `**Execution Status:** TODO / Not Executed`,
    `**Initial Status:** All tests are in TODO state — no test has been marked Passed or Failed`,
    `\n---\n*Auto-created by the Jira Xray Excel Test Case Generator Agent*`,
  ].join("\n");

  const result = await callJiraTool(client, "createJiraIssue", {
    cloudId,
    projectKey,
    summary,
    description,
    issueType: XRAY_TEST_EXECUTION_TYPE_NAME,
    priority: "Medium",
  });

  const key = result?.key || result?.issueKey;
  const id  = result?.id;

  if (!key) {
    throw new Error(`createJiraIssue did not return a key for Test Execution issue`);
  }

  // Link each test to the execution using "Test" link type
  for (const testKey of testKeys) {
    try {
      await callJiraTool(client, "createJiraIssueLink", {
        cloudId,
        linkType: XRAY_LINK_TYPE_NAME,
        inwardIssue: testKey,
        outwardIssue: key,
      });
    } catch {
      // Non-fatal — log but continue
      console.warn(`Warning: Could not link ${testKey} to execution ${key}`);
    }
  }

  return { key, id };
}
